"""Split a processed text-label dataset file into train/validation/test exports."""

from __future__ import annotations

import random
from pathlib import Path
from typing import Any

import click
import torch

from kpi.utils.stb_supervised import load_processed_samples, validate_split_ratios


def _split_indices(total_size: int, ratios: tuple[float, float, float], seed: int) -> tuple[list[int], list[int], list[int]]:
    indices = list(range(total_size))
    random.Random(seed).shuffle(indices)

    train_end = int(ratios[0] * total_size)
    val_end = train_end + int(ratios[1] * total_size)

    train_idx = indices[:train_end]
    val_idx = indices[train_end:val_end]
    test_idx = indices[val_end:]
    return train_idx, val_idx, test_idx


def _build_payload(
    samples: list[dict[str, Any]],
    selected_indices: list[int],
    split_name: str,
    seed: int,
    ratios: tuple[float, float, float],
    source_path: str,
) -> dict[str, Any]:
    return {
        "version": 1,
        "source": source_path,
        "seed": seed,
        "ratios": {
            "train": ratios[0],
            "validation": ratios[1],
            "test": ratios[2],
        },
        "split": split_name,
        "samples": [samples[idx] for idx in selected_indices],
    }


@click.command()
@click.option(
    "--input_path",
    type=str,
    default="processed_dataset/mitfld_processed.pt",
    show_default=True,
    help="Path to processed dataset file generated by export_text_label_dataset.py.",
)
@click.option(
    "--output_dir",
    type=str,
    default="processed_dataset/mitfld_split",
    show_default=True,
    help="Directory to save split .pt files.",
)
@click.option("--seed", type=int, default=2024, show_default=True)
@click.option("--train_ratio", type=float, default=0.7, show_default=True)
@click.option("--val_ratio", type=float, default=0.15, show_default=True)
@click.option("--test_ratio", type=float, default=0.15, show_default=True)
def main(
    input_path: str,
    output_dir: str,
    seed: int,
    train_ratio: float,
    val_ratio: float,
    test_ratio: float,
) -> None:
    """Split processed dataset by seed and export split files."""

    validate_split_ratios(train_ratio, val_ratio, test_ratio)
    samples = load_processed_samples(input_path)
    total_size = len(samples)
    if total_size < 3:
        raise click.BadParameter("Need at least 3 samples to split into train/validation/test")

    ratios = (train_ratio, val_ratio, test_ratio)
    train_idx, val_idx, test_idx = _split_indices(total_size=total_size, ratios=ratios, seed=seed)

    if not train_idx or not val_idx or not test_idx:
        raise click.BadParameter(
            "One split became empty. Adjust ratios or provide a larger dataset."
        )

    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    split_map = {
        "train": train_idx,
        "validation": val_idx,
        "test": test_idx,
    }
    for split_name, split_indices in split_map.items():
        payload = _build_payload(
            samples=samples,
            selected_indices=split_indices,
            split_name=split_name,
            seed=seed,
            ratios=ratios,
            source_path=str(input_path),
        )
        out_path = out_dir / f"mitfld_processed_{split_name}.pt"
        torch.save(payload, out_path)
        print(f"Saved {split_name}: {len(split_indices)} samples -> {out_path}")


if __name__ == "__main__":
    main()
